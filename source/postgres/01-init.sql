-- Exact PDF source schema; optional simulator-owned queue lives in a separate schema.
CREATE SCHEMA core;
CREATE SCHEMA simulator;

CREATE TABLE core.merchants (
  merchant_id BIGINT PRIMARY KEY,
  name TEXT NOT NULL,
  mcc VARCHAR(4) NOT NULL,
  province TEXT NOT NULL,
  risk_level TEXT NOT NULL CHECK (risk_level IN ('LOW','MEDIUM','HIGH')),
  owner_national_id VARCHAR(10) NOT NULL,
  owner_mobile VARCHAR(11) NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE core.transactions (
  transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  merchant_id BIGINT NOT NULL REFERENCES core.merchants(merchant_id),
  channel TEXT NOT NULL CHECK (channel IN ('POS','IPG','QR')),
  card_bin VARCHAR(6) NOT NULL,
  amount BIGINT NOT NULL CHECK (amount > 0),
  fee_amount BIGINT NOT NULL CHECK (fee_amount >= 0),
  status TEXT NOT NULL CHECK (status IN ('PENDING','SUCCESS','FAILED','REVERSED')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);

-- The queue is source-simulator bookkeeping, NOT part of core CDC publication.
-- A transaction and its future action are committed atomically; restarts retain work.
CREATE TABLE simulator.pending_actions (
  transaction_id BIGINT PRIMARY KEY REFERENCES core.transactions(transaction_id) ON DELETE CASCADE,
  action TEXT NOT NULL CHECK (action IN ('settle','reverse','test_delete')),
  due_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX simulator_pending_due_idx ON simulator.pending_actions(due_at);

CREATE FUNCTION core.touch_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := clock_timestamp();
  RETURN NEW;
END $$;
CREATE TRIGGER merchants_touch BEFORE UPDATE ON core.merchants
  FOR EACH ROW EXECUTE FUNCTION core.touch_updated_at();
CREATE TRIGGER transactions_touch BEFORE UPDATE ON core.transactions
  FOR EACH ROW EXECUTE FUNCTION core.touch_updated_at();

ALTER TABLE core.merchants REPLICA IDENTITY FULL;
ALTER TABLE core.transactions REPLICA IDENTITY FULL;

